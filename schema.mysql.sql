-- =======================================================
-- KHETSETU DATABASE SCHEMA FOR MYSQL
-- =======================================================

CREATE DATABASE IF NOT EXISTS khetsetu CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE khetsetu;

-- 1. Users table
CREATE TABLE IF NOT EXISTS User (
  id VARCHAR(191) PRIMARY KEY,
  email VARCHAR(191) UNIQUE NOT NULL,
  phone VARCHAR(191) UNIQUE NOT NULL,
  passwordHash VARCHAR(191) NOT NULL,
  name VARCHAR(191) NOT NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'FARMER',
  isVerified BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
  avatarUrl TEXT,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX idx_user_role (role),
  INDEX idx_user_status (status)
) ENGINE=InnoDB;

-- 2. Farmer Profiles
CREATE TABLE IF NOT EXISTS FarmerProfile (
  id VARCHAR(191) PRIMARY KEY,
  userId VARCHAR(191) UNIQUE NOT NULL,
  village VARCHAR(191) NOT NULL,
  district VARCHAR(191) NOT NULL,
  state VARCHAR(191) NOT NULL,
  pincode VARCHAR(50) NOT NULL,
  farmAreaAcres DOUBLE NOT NULL DEFAULT 5.0,
  experienceYears INT NOT NULL DEFAULT 5,
  soilType VARCHAR(191) NOT NULL DEFAULT 'Alluvial / Loamy',
  primaryCrops VARCHAR(191) NOT NULL DEFAULT 'Wheat, Mustard, Soybean',
  kisanCreditCardNo VARCHAR(191),
  verifiedBadge BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 3. Buyer Profiles
CREATE TABLE IF NOT EXISTS BuyerProfile (
  id VARCHAR(191) PRIMARY KEY,
  userId VARCHAR(191) UNIQUE NOT NULL,
  companyName VARCHAR(191) NOT NULL,
  businessType VARCHAR(50) NOT NULL DEFAULT 'WHOLESALER',
  gstin VARCHAR(191),
  city VARCHAR(191) NOT NULL,
  district VARCHAR(191) NOT NULL,
  state VARCHAR(191) NOT NULL,
  pincode VARCHAR(50) NOT NULL,
  tradeLicense VARCHAR(191),
  verifiedBadge BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 4. Farm Locations
CREATE TABLE IF NOT EXISTS FarmLocation (
  id VARCHAR(191) PRIMARY KEY,
  farmerId VARCHAR(191) NOT NULL,
  label VARCHAR(191) NOT NULL DEFAULT 'Main Farm',
  latitude DOUBLE NOT NULL,
  longitude DOUBLE NOT NULL,
  address VARCHAR(255) NOT NULL,
  village VARCHAR(191) NOT NULL,
  district VARCHAR(191) NOT NULL,
  state VARCHAR(191) NOT NULL,
  pincode VARCHAR(50) NOT NULL,
  FOREIGN KEY (farmerId) REFERENCES FarmerProfile(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 5. Crop Categories
CREATE TABLE IF NOT EXISTS CropCategory (
  id VARCHAR(191) PRIMARY KEY,
  name VARCHAR(191) UNIQUE NOT NULL,
  slug VARCHAR(191) UNIQUE NOT NULL,
  description TEXT,
  icon VARCHAR(191)
) ENGINE=InnoDB;

-- 6. Crop Listings
CREATE TABLE IF NOT EXISTS CropListing (
  id VARCHAR(191) PRIMARY KEY,
  farmerId VARCHAR(191) NOT NULL,
  categoryId VARCHAR(191) NOT NULL,
  cropName VARCHAR(191) NOT NULL,
  variety VARCHAR(191),
  description TEXT NOT NULL,
  quantity DOUBLE NOT NULL,
  unit VARCHAR(50) NOT NULL DEFAULT 'kg',
  pricePerKg DOUBLE NOT NULL,
  qualityGrade VARCHAR(50) NOT NULL DEFAULT 'GRADE_A',
  harvestDate DATETIME(3) NOT NULL,
  availableUntil DATETIME(3) NOT NULL,
  farmLocationId VARCHAR(191),
  deliveryRadiusKm DOUBLE NOT NULL DEFAULT 50.0,
  status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
  viewsCount INT NOT NULL DEFAULT 0,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (farmerId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (categoryId) REFERENCES CropCategory(id),
  FOREIGN KEY (farmLocationId) REFERENCES FarmLocation(id) ON DELETE SET NULL,
  INDEX idx_listing_crop (cropName),
  INDEX idx_listing_grade (qualityGrade),
  INDEX idx_listing_status (status)
) ENGINE=InnoDB;

-- 7. Crop Images
CREATE TABLE IF NOT EXISTS CropImage (
  id VARCHAR(191) PRIMARY KEY,
  listingId VARCHAR(191) NOT NULL,
  imageUrl TEXT NOT NULL,
  isPrimary BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (listingId) REFERENCES CropListing(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 8. Buyer Requirements (Intelligent Procurement)
CREATE TABLE IF NOT EXISTS BuyerRequirement (
  id VARCHAR(191) PRIMARY KEY,
  buyerId VARCHAR(191) NOT NULL,
  cropName VARCHAR(191) NOT NULL,
  requiredQuantity DOUBLE NOT NULL,
  unit VARCHAR(50) NOT NULL DEFAULT 'kg',
  qualityGrade VARCHAR(50) NOT NULL DEFAULT 'GRADE_A',
  minPrice DOUBLE NOT NULL DEFAULT 0.0,
  maxPrice DOUBLE NOT NULL,
  maxDistanceKm DOUBLE NOT NULL DEFAULT 100.0,
  deliveryDeadline DATETIME(3) NOT NULL,
  preferredLocation VARCHAR(191) NOT NULL,
  deliveryAddress VARCHAR(255) NOT NULL,
  latitude DOUBLE NOT NULL DEFAULT 22.7196,
  longitude DOUBLE NOT NULL DEFAULT 75.8577,
  notes TEXT,
  status VARCHAR(50) NOT NULL DEFAULT 'OPEN',
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (buyerId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 9. Procurement Plans
CREATE TABLE IF NOT EXISTS ProcurementPlan (
  id VARCHAR(191) PRIMARY KEY,
  requirementId VARCHAR(191) NOT NULL,
  buyerId VARCHAR(191) NOT NULL,
  totalRequiredQty DOUBLE NOT NULL,
  totalMatchedQty DOUBLE NOT NULL,
  remainingShortage DOUBLE NOT NULL,
  totalEstimatedCost DOUBLE NOT NULL,
  weightedAvgPrice DOUBLE NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
  notes TEXT,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (requirementId) REFERENCES BuyerRequirement(id) ON DELETE CASCADE,
  FOREIGN KEY (buyerId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 10. Procurement Plan Items (Individual Farmer Contribution)
CREATE TABLE IF NOT EXISTS ProcurementPlanItem (
  id VARCHAR(191) PRIMARY KEY,
  planId VARCHAR(191) NOT NULL,
  listingId VARCHAR(191) NOT NULL,
  farmerId VARCHAR(191) NOT NULL,
  allocatedQty DOUBLE NOT NULL,
  pricePerKg DOUBLE NOT NULL,
  itemTotalCost DOUBLE NOT NULL,
  distanceKm DOUBLE NOT NULL,
  fulfillmentTimelineDays INT NOT NULL,
  reasonSelected TEXT NOT NULL,
  FOREIGN KEY (planId) REFERENCES ProcurementPlan(id) ON DELETE CASCADE,
  FOREIGN KEY (listingId) REFERENCES CropListing(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 11. Bids and Negotiations
CREATE TABLE IF NOT EXISTS Bid (
  id VARCHAR(191) PRIMARY KEY,
  listingId VARCHAR(191) NOT NULL,
  buyerId VARCHAR(191) NOT NULL,
  offeredPrice DOUBLE NOT NULL,
  quantity DOUBLE NOT NULL,
  message TEXT,
  counterPrice DOUBLE,
  counterMessage TEXT,
  status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (listingId) REFERENCES CropListing(id) ON DELETE CASCADE,
  FOREIGN KEY (buyerId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 12. Conversations & Messages
CREATE TABLE IF NOT EXISTS Conversation (
  id VARCHAR(191) PRIMARY KEY,
  farmerId VARCHAR(191) NOT NULL,
  buyerId VARCHAR(191) NOT NULL,
  listingId VARCHAR(191),
  lastMessageAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (farmerId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (buyerId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (listingId) REFERENCES CropListing(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Message (
  id VARCHAR(191) PRIMARY KEY,
  conversationId VARCHAR(191) NOT NULL,
  senderId VARCHAR(191) NOT NULL,
  text TEXT NOT NULL,
  isRead BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (conversationId) REFERENCES Conversation(id) ON DELETE CASCADE,
  FOREIGN KEY (senderId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 13. Orders & Items
CREATE TABLE IF NOT EXISTS `Order` (
  id VARCHAR(191) PRIMARY KEY,
  orderNumber VARCHAR(191) UNIQUE NOT NULL,
  buyerId VARCHAR(191) NOT NULL,
  planId VARCHAR(191),
  totalAmount DOUBLE NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
  deliveryAddress TEXT NOT NULL,
  latitude DOUBLE,
  longitude DOUBLE,
  paymentStatus VARCHAR(50) NOT NULL DEFAULT 'PENDING',
  paymentMethod VARCHAR(50) NOT NULL DEFAULT 'UPI / Escrow',
  notes TEXT,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (buyerId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (planId) REFERENCES ProcurementPlan(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS OrderItem (
  id VARCHAR(191) PRIMARY KEY,
  orderId VARCHAR(191) NOT NULL,
  listingId VARCHAR(191) NOT NULL,
  farmerId VARCHAR(191) NOT NULL,
  quantity DOUBLE NOT NULL,
  unitPrice DOUBLE NOT NULL,
  totalPrice DOUBLE NOT NULL,
  itemStatus VARCHAR(50) NOT NULL DEFAULT 'CONFIRMED',
  trackingNumber VARCHAR(191),
  dispatchedAt DATETIME(3),
  deliveredAt DATETIME(3),
  FOREIGN KEY (orderId) REFERENCES `Order`(id) ON DELETE CASCADE,
  FOREIGN KEY (listingId) REFERENCES CropListing(id) ON DELETE CASCADE,
  FOREIGN KEY (farmerId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 14. Notifications, Weather, Market Prices, Advisories, Queries, Disputes
CREATE TABLE IF NOT EXISTS Notification (
  id VARCHAR(191) PRIMARY KEY,
  userId VARCHAR(191) NOT NULL,
  title VARCHAR(191) NOT NULL,
  message TEXT NOT NULL,
  type VARCHAR(50) NOT NULL DEFAULT 'INFO',
  isRead BOOLEAN NOT NULL DEFAULT FALSE,
  link VARCHAR(255),
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS WeatherRecord (
  id VARCHAR(191) PRIMARY KEY,
  location VARCHAR(191) NOT NULL,
  district VARCHAR(191) NOT NULL,
  state VARCHAR(191) NOT NULL,
  temperature DOUBLE NOT NULL,
  `condition` VARCHAR(191) NOT NULL,
  humidity INT NOT NULL,
  rainProb INT NOT NULL,
  windSpeed DOUBLE NOT NULL,
  forecastJson TEXT,
  recordedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS MarketPrice (
  id VARCHAR(191) PRIMARY KEY,
  commodity VARCHAR(191) NOT NULL,
  state VARCHAR(191) NOT NULL,
  district VARCHAR(191) NOT NULL,
  marketName VARCHAR(191) NOT NULL,
  minPrice DOUBLE NOT NULL,
  maxPrice DOUBLE NOT NULL,
  modalPrice DOUBLE NOT NULL,
  priceDate DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  source VARCHAR(191) NOT NULL DEFAULT 'Agmarknet / Demo Mandi Feed',
  isVerifiedGov BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS AgriculturalAdvisory (
  id VARCHAR(191) PRIMARY KEY,
  title VARCHAR(191) NOT NULL,
  category VARCHAR(50) NOT NULL,
  cropName VARCHAR(191) NOT NULL,
  description TEXT NOT NULL,
  symptoms TEXT,
  solution TEXT NOT NULL,
  preventiveMeasures TEXT,
  seasonalTiming VARCHAR(191),
  severity VARCHAR(50) NOT NULL DEFAULT 'MODERATE',
  imageUrl TEXT,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS FarmingQuery (
  id VARCHAR(191) PRIMARY KEY,
  farmerId VARCHAR(191) NOT NULL,
  cropName VARCHAR(191) NOT NULL,
  queryText TEXT NOT NULL,
  imageUrl TEXT,
  status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
  aiResponse TEXT,
  expertResponse TEXT,
  answeredAt DATETIME(3),
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (farmerId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS Dispute (
  id VARCHAR(191) PRIMARY KEY,
  orderId VARCHAR(191) NOT NULL,
  raisedById VARCHAR(191) NOT NULL,
  againstUserId VARCHAR(191) NOT NULL,
  reason VARCHAR(191) NOT NULL,
  description TEXT NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'OPEN',
  adminResolution TEXT,
  resolvedAt DATETIME(3),
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (orderId) REFERENCES `Order`(id) ON DELETE CASCADE,
  FOREIGN KEY (raisedById) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (againstUserId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS VerificationRequest (
  id VARCHAR(191) PRIMARY KEY,
  userId VARCHAR(191) NOT NULL,
  role VARCHAR(50) NOT NULL,
  documentType VARCHAR(50) NOT NULL,
  documentNumber VARCHAR(191) NOT NULL,
  documentUrl TEXT,
  status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
  adminNotes TEXT,
  reviewedAt DATETIME(3),
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE
) ENGINE=InnoDB;
