import React, { useState, useEffect } from 'react';
import { useSearchParams, useNavigate } from 'react-router-dom';
import { useAuth } from '../../context/AuthContext';
import {
  Sparkles,
  MapPin,
  Clock,
  ShieldCheck,
  TrendingUp,
  CheckCircle2,
  AlertCircle,
  Truck,
  ArrowRight,
  Calculator,
  Layers,
  Info,
  Calendar,
  Building,
} from 'lucide-react';
import api from '../../services/api';

export const IntelligentProcurementPage: React.FC = () => {
  const { user } = useAuth();
  const navigate = useNavigate();
  const [searchParams] = useSearchParams();

  // Form State
  const [cropName, setCropName] = useState(searchParams.get('crop') || 'Wheat');
  const [requiredQuantity, setRequiredQuantity] = useState(searchParams.get('qty') || '1000');
  const [qualityGrade, setQualityGrade] = useState('GRADE_A');
  const [minPrice, setMinPrice] = useState('20');
  const [maxPrice, setMaxPrice] = useState(searchParams.get('maxPrice') || '30');
  const [maxDistanceKm, setMaxDistanceKm] = useState('70');
  const [deliveryDays, setDeliveryDays] = useState('5');
  const [deliveryAddress, setDeliveryAddress] = useState(
    'Central Grain Warehouse, Sanwer Road Industrial Area, Indore 452015'
  );
  const [buyerLat, setBuyerLat] = useState('22.7196');
  const [buyerLng, setBuyerLng] = useState('75.8577');
  const [strategy, setStrategy] = useState<'BALANCED' | 'LOWEST_PRICE' | 'SHORTEST_DISTANCE'>('BALANCED');

  // Execution & Result State
  const [isMatching, setIsMatching] = useState(false);
  const [result, setResult] = useState<any | null>(null);
  const [error, setError] = useState('');
  const [isConfirming, setIsConfirming] = useState(false);
  const [confirmationSuccess, setConfirmationSuccess] = useState<any | null>(null);

  // Auto-run if query params present
  useEffect(() => {
    if (searchParams.get('crop') || searchParams.get('qty')) {
      handleExecuteMatching();
    }
  }, []);

  const handleExecuteMatching = async (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    setError('');
    setConfirmationSuccess(null);
    setIsMatching(true);

    try {
      const deadline = new Date(Date.now() + Number(deliveryDays) * 24 * 60 * 60 * 1000).toISOString();

      const res = await api.post('/procurement/match', {
        cropName,
        requiredQuantity: Number(requiredQuantity),
        qualityGrade,
        minPrice: Number(minPrice),
        maxPrice: Number(maxPrice),
        maxDistanceKm: Number(maxDistanceKm),
        deliveryDeadline: deadline,
        buyerLat: Number(buyerLat),
        buyerLng: Number(buyerLng),
        strategy,
      });

      setResult(res.data);
    } catch (err: any) {
      setError(err.response?.data?.message || 'Error running matching algorithm');
    } finally {
      setIsMatching(false);
    }
  };

  const handleConfirmPlan = async () => {
    if (!user) {
      setError('Please sign in to save and confirm your procurement plan');
      navigate('/login');
      return;
    }

    if (!result || result.items.length === 0) return;

    setIsConfirming(true);
    setError('');

    try {
      // 1. Create requirement first
      const reqRes = await api.post('/procurement/requirements', {
        cropName: result.cropName,
        requiredQuantity: result.totalRequiredQty,
        qualityGrade,
        minPrice: Number(minPrice),
        maxPrice: Number(maxPrice),
        maxDistanceKm: Number(maxDistanceKm),
        deliveryDeadline: new Date(Date.now() + Number(deliveryDays) * 24 * 60 * 60 * 1000),
        preferredLocation: 'Indore Central Hub',
        deliveryAddress,
        latitude: Number(buyerLat),
        longitude: Number(buyerLng),
        notes: `Procurement generated by Intelligent Matching Engine (${strategy})`,
      });

      const requirementId = reqRes.data.requirement.id;

      // 2. Confirm Plan
      const planRes = await api.post('/procurement/plans/confirm', {
        requirementId,
        totalRequiredQty: result.totalRequiredQty,
        totalMatchedQty: result.totalMatchedQty,
        remainingShortage: result.remainingShortage,
        totalEstimatedCost: result.totalEstimatedCost,
        weightedAvgPrice: result.weightedAvgPrice,
        items: result.items,
        notes: result.explanationSummary,
      });

      setConfirmationSuccess(planRes.data.plan);
    } catch (err: any) {
      setError(err.response?.data?.message || 'Failed to confirm plan');
    } finally {
      setIsConfirming(false);
    }
  };

  const handleConvertToOrder = async (planId: string) => {
    try {
      setIsConfirming(true);
      const res = await api.post(`/procurement/plans/${planId}/order`, {
        deliveryAddress,
        paymentMethod: 'UPI / Escrow',
      });
      navigate(`/buyer/orders?orderId=${res.data.order.id}`);
    } catch (err: any) {
      setError(err.response?.data?.message || 'Failed to convert plan to order');
    } finally {
      setIsConfirming(false);
    }
  };

  return (
    <div className="max-w-7xl mx-auto space-y-8 pb-12">
      {/* Header Banner */}
      <div className="bg-gradient-to-r from-agri-dark to-agri-forest text-white p-6 sm:p-8 rounded-3xl shadow-xl relative overflow-hidden">
        <div className="max-w-3xl space-y-2 relative z-10">
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-white/10 backdrop-blur-md text-amber-300 text-xs font-bold border border-white/20">
            <Sparkles className="w-3.5 h-3.5" />
            <span>KhetSetu Flagship Innovation</span>
          </div>
          <h1 className="text-2xl sm:text-4xl font-extrabold tracking-tight">
            Intelligent Multi-Farmer Procurement Matching Engine
          </h1>
          <p className="text-xs sm:text-sm text-agri-100 leading-relaxed">
            Eliminates fragmented lot searching. Enter your required crop, tonnage, and delivery constraints.
            Our algorithm scans all verified local farmers, computes geo-distances, aggregates smallholder supply,
            and generates an optimal procurement plan with itemized farmer allocations.
          </p>
        </div>
      </div>

      {/* Main Grid: Parameters Form & Match Results */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">
        {/* Left: Input Parameters (4 cols on lg) */}
        <div className="lg:col-span-5 bg-white p-6 rounded-3xl border border-warm-border shadow-sm space-y-5">
          <div className="flex items-center justify-between border-b border-slate-100 pb-3">
            <h2 className="text-base font-extrabold text-slate-900 flex items-center gap-2">
              <Calculator className="w-5 h-5 text-agri-dark" />
              <span>Procurement Parameters</span>
            </h2>
            <span className="text-[11px] font-bold text-agri-700 bg-agri-50 px-2.5 py-0.5 rounded-full">
              Live DB Scanner
            </span>
          </div>

          <form onSubmit={handleExecuteMatching} className="space-y-4">
            <div>
              <label className="block text-xs font-bold text-slate-700 mb-1">Crop Commodity</label>
              <select
                value={cropName}
                onChange={(e) => setCropName(e.target.value)}
                className="w-full text-xs font-bold px-3 py-2.5 rounded-xl border border-slate-200 bg-slate-50 focus:ring-2 focus:ring-agri-leaf"
              >
                <option value="Wheat">Wheat (Sharbati / Lokwan)</option>
                <option value="Soybean">Soybean (JS-9560 / NRC)</option>
                <option value="Rice">Rice (Pusa 1121 Paddy)</option>
                <option value="Onion">Onion (Nashik Red)</option>
                <option value="Tomato">Tomato (Hybrid Processing)</option>
                <option value="Cotton">Cotton (Shankar-6)</option>
                <option value="Desi Chana (Chickpea)">Desi Chana (Chickpea)</option>
              </select>
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Target Quantity (kg)</label>
                <input
                  type="number"
                  required
                  value={requiredQuantity}
                  onChange={(e) => setRequiredQuantity(e.target.value)}
                  min="50"
                  step="50"
                  className="w-full text-xs font-bold px-3 py-2 rounded-xl border border-slate-200 focus:ring-2 focus:ring-agri-leaf"
                />
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Quality Grade</label>
                <select
                  value={qualityGrade}
                  onChange={(e) => setQualityGrade(e.target.value)}
                  className="w-full text-xs font-bold px-3 py-2 rounded-xl border border-slate-200 bg-white"
                >
                  <option value="GRADE_A">Grade A (Export / Prime)</option>
                  <option value="GRADE_B">Grade B (Standard)</option>
                  <option value="GRADE_C">Grade C (Industrial / Feed)</option>
                  <option value="ANY">Any Acceptable Grade</option>
                </select>
              </div>
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Max Budget Price (₹/kg)</label>
                <input
                  type="number"
                  required
                  value={maxPrice}
                  onChange={(e) => setMaxPrice(e.target.value)}
                  min="5"
                  className="w-full text-xs font-bold px-3 py-2 rounded-xl border border-slate-200 focus:ring-2 focus:ring-agri-leaf"
                />
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Max Distance Radius (km)</label>
                <input
                  type="number"
                  required
                  value={maxDistanceKm}
                  onChange={(e) => setMaxDistanceKm(e.target.value)}
                  min="10"
                  max="500"
                  className="w-full text-xs font-bold px-3 py-2 rounded-xl border border-slate-200 focus:ring-2 focus:ring-agri-leaf"
                />
              </div>
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Delivery Window</label>
                <select
                  value={deliveryDays}
                  onChange={(e) => setDeliveryDays(e.target.value)}
                  className="w-full text-xs font-bold px-3 py-2 rounded-xl border border-slate-200 bg-white"
                >
                  <option value="2">Within 2 Days</option>
                  <option value="3">Within 3 Days</option>
                  <option value="5">Within 5 Days</option>
                  <option value="7">Within 7 Days</option>
                  <option value="14">Within 14 Days</option>
                </select>
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Optimization Goal</label>
                <select
                  value={strategy}
                  onChange={(e) => setStrategy(e.target.value as any)}
                  className="w-full text-xs font-bold px-3 py-2 rounded-xl border border-slate-200 bg-white"
                >
                  <option value="BALANCED">Balanced (Cost + Distance)</option>
                  <option value="LOWEST_PRICE">Lowest Procurement Cost</option>
                  <option value="SHORTEST_DISTANCE">Shortest Transit Distance</option>
                </select>
              </div>
            </div>

            <div>
              <label className="block text-xs font-bold text-slate-700 mb-1">Destination Warehouse Address</label>
              <input
                type="text"
                required
                value={deliveryAddress}
                onChange={(e) => setDeliveryAddress(e.target.value)}
                className="w-full text-xs font-semibold px-3 py-2 rounded-xl border border-slate-200 focus:ring-2 focus:ring-agri-leaf"
              />
            </div>

            <button
              type="submit"
              disabled={isMatching}
              className="w-full py-3.5 rounded-2xl text-xs font-extrabold text-white bg-agri-dark hover:bg-agri-forest shadow-md transition flex items-center justify-center gap-2 disabled:opacity-50"
            >
              <Sparkles className="w-4 h-4 text-amber-300" />
              <span>{isMatching ? 'Running Multi-Farmer Matcher...' : 'Compute Optimal Supply Plan'}</span>
            </button>
          </form>
        </div>

        {/* Right: Procurement Result & Farmer Contribution Breakdown (7 cols on lg) */}
        <div className="lg:col-span-7 space-y-6">
          {error && (
            <div className="p-4 rounded-2xl bg-rose-50 border border-rose-200 text-xs text-rose-700 font-medium flex items-center gap-2">
              <AlertCircle className="w-5 h-5 text-rose-500 shrink-0" />
              <span>{error}</span>
            </div>
          )}

          {/* Result Card */}
          {result ? (
            <div className="bg-white rounded-3xl border border-warm-border p-6 shadow-sm space-y-6">
              {/* Top Fulfillment Badge */}
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-100">
                <div>
                  <span className="text-[11px] font-bold uppercase tracking-wider text-slate-400">
                    Aggregation Outcome
                  </span>
                  <h3 className="text-xl font-black text-slate-900 mt-0.5">
                    {result.isFullyFulfilled ? '100% Demand Fulfilled' : 'Partial Match Found'}
                  </h3>
                </div>

                <div className="flex items-center gap-2">
                  <div
                    className={`px-3 py-1.5 rounded-xl text-xs font-extrabold flex items-center gap-1.5 ${
                      result.isFullyFulfilled
                        ? 'bg-emerald-100 text-emerald-800 border border-emerald-300'
                        : 'bg-amber-100 text-amber-800 border border-amber-300'
                    }`}
                  >
                    <CheckCircle2 className="w-4 h-4" />
                    <span>{result.fulfillmentPercentage}% Fulfilled</span>
                  </div>
                </div>
              </div>

              {/* Progress Bar of Fulfillment */}
              <div>
                <div className="flex justify-between text-xs font-bold text-slate-700 mb-1.5">
                  <span>
                    Matched: <strong>{result.totalMatchedQty} kg</strong> / {result.totalRequiredQty} kg
                  </span>
                  {result.remainingShortage > 0 && (
                    <span className="text-amber-700">
                      Shortage: <strong>{result.remainingShortage} kg</strong>
                    </span>
                  )}
                </div>
                <div className="w-full h-3 bg-slate-100 rounded-full overflow-hidden">
                  <div
                    className={`h-full rounded-full transition-all duration-500 ${
                      result.isFullyFulfilled ? 'bg-emerald-500' : 'bg-amber-500'
                    }`}
                    style={{ width: `${Math.min(100, result.fulfillmentPercentage)}%` }}
                  ></div>
                </div>
              </div>

              {/* KPI Summary Cards */}
              <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
                <div className="p-3.5 rounded-2xl bg-slate-50 border border-slate-100">
                  <span className="text-[10px] font-bold text-slate-400 uppercase">Weighted Avg Price</span>
                  <p className="text-base font-black text-agri-dark mt-0.5">₹{result.weightedAvgPrice}/kg</p>
                  <span className="text-[10px] text-emerald-600 font-semibold">Under ₹{maxPrice} cap</span>
                </div>

                <div className="p-3.5 rounded-2xl bg-slate-50 border border-slate-100">
                  <span className="text-[10px] font-bold text-slate-400 uppercase">Total Plan Cost</span>
                  <p className="text-base font-black text-slate-900 mt-0.5">
                    ₹{result.totalEstimatedCost.toLocaleString()}
                  </p>
                  <span className="text-[10px] text-slate-500 font-medium">All lots combined</span>
                </div>

                <div className="p-3.5 rounded-2xl bg-slate-50 border border-slate-100">
                  <span className="text-[10px] font-bold text-slate-400 uppercase">Farmers Combined</span>
                  <p className="text-base font-black text-slate-900 mt-0.5">{result.farmerCount} Farmers</p>
                  <span className="text-[10px] text-slate-500 font-medium">Local aggregator</span>
                </div>

                <div className="p-3.5 rounded-2xl bg-slate-50 border border-slate-100">
                  <span className="text-[10px] font-bold text-slate-400 uppercase">Avg Distance</span>
                  <p className="text-base font-black text-slate-900 mt-0.5">{result.averageDistanceKm} km</p>
                  <span className="text-[10px] text-sky-600 font-semibold">~{result.estimatedDeliveryTimelineDays} Days transit</span>
                </div>
              </div>

              {/* Algorithmic Explanation Note */}
              <div className="p-3.5 rounded-2xl bg-agri-50 border border-agri-200 text-xs text-agri-900">
                <span className="font-extrabold flex items-center gap-1.5 mb-1">
                  <Info className="w-4 h-4 text-agri-700" />
                  Algorithm Explanation:
                </span>
                <p className="text-[11px] leading-relaxed text-agri-800">{result.explanationSummary}</p>
              </div>

              {/* Itemized Farmer Allocations Breakdown */}
              <div className="space-y-3">
                <h4 className="text-xs font-extrabold uppercase tracking-wider text-slate-700">
                  Farmer Supply Breakdown ({result.items.length} Selected Lots)
                </h4>

                <div className="space-y-2.5">
                  {result.items.map((item: any, idx: number) => (
                    <div
                      key={idx}
                      className="p-4 rounded-2xl border border-slate-200 hover:border-agri-400 transition bg-white space-y-2"
                    >
                      <div className="flex items-start justify-between">
                        <div>
                          <div className="flex items-center gap-2">
                            <span className="w-5 h-5 rounded-full bg-agri-dark text-white text-[10px] font-bold flex items-center justify-center">
                              {idx + 1}
                            </span>
                            <span className="font-extrabold text-sm text-slate-900">{item.farmerName}</span>
                            {item.verifiedBadge && (
                              <span className="inline-flex items-center text-[10px] font-bold text-emerald-700 bg-emerald-50 px-1.5 py-0.2 rounded">
                                <ShieldCheck className="w-3 h-3 text-emerald-600" /> KYC Verified
                              </span>
                            )}
                          </div>
                          <p className="text-[11px] text-slate-500 flex items-center gap-1 mt-0.5">
                            <MapPin className="w-3 h-3 text-slate-400" />
                            {item.farmLocation} • {item.distanceKm} km away
                          </p>
                        </div>

                        <div className="text-right">
                          <span className="text-sm font-black text-slate-900">
                            {item.allocatedQty} kg @ ₹{item.pricePerKg}/kg
                          </span>
                          <p className="text-[11px] font-bold text-agri-700">
                            Total: ₹{item.itemTotalCost.toLocaleString()}
                          </p>
                        </div>
                      </div>

                      {/* Reason badge */}
                      <div className="pt-2 border-t border-slate-100 text-[10px] text-slate-600 font-medium">
                        <strong>Reason Selected:</strong> {item.reasonSelected}
                      </div>
                    </div>
                  ))}
                </div>
              </div>

              {/* Confirmation and Order Buttons */}
              <div className="pt-4 border-t border-slate-100 flex flex-col sm:flex-row items-center gap-3">
                {!confirmationSuccess ? (
                  <button
                    onClick={handleConfirmPlan}
                    disabled={isConfirming}
                    className="w-full sm:flex-1 py-3.5 rounded-2xl text-xs font-extrabold text-white bg-agri-dark hover:bg-agri-forest shadow-md transition flex items-center justify-center gap-2 disabled:opacity-50"
                  >
                    <CheckCircle2 className="w-4 h-4 text-emerald-400" />
                    <span>{isConfirming ? 'Confirming Plan...' : 'Confirm Procurement Plan'}</span>
                  </button>
                ) : (
                  <div className="w-full space-y-3">
                    <div className="p-3 rounded-2xl bg-emerald-50 border border-emerald-300 text-xs text-emerald-800 font-bold flex items-center gap-2">
                      <CheckCircle2 className="w-5 h-5 text-emerald-600 shrink-0" />
                      <span>
                        Procurement Plan #{confirmationSuccess.id.slice(0, 8)} confirmed and saved!
                      </span>
                    </div>
                    <button
                      onClick={() => handleConvertToOrder(confirmationSuccess.id)}
                      disabled={isConfirming}
                      className="w-full py-3.5 rounded-2xl text-xs font-black text-slate-900 bg-amber-400 hover:bg-amber-300 shadow-md transition flex items-center justify-center gap-2"
                    >
                      <Truck className="w-4 h-4 text-slate-900" />
                      <span>Convert to Active Order with Escrow (₹{result.totalEstimatedCost.toLocaleString()})</span>
                      <ArrowRight className="w-4 h-4" />
                    </button>
                  </div>
                )}
              </div>
            </div>
          ) : (
            <div className="bg-white rounded-3xl border border-warm-border p-12 text-center space-y-3">
              <div className="w-14 h-14 rounded-2xl bg-amber-100 text-amber-800 flex items-center justify-center mx-auto">
                <Sparkles className="w-7 h-7 text-amber-600" />
              </div>
              <h3 className="text-base font-extrabold text-slate-900">Procurement Result Ready for Generation</h3>
              <p className="text-xs text-slate-500 max-w-md mx-auto">
                Configure your target crop, tonnage, and budget on the left, then click "Compute Optimal Supply Plan"
                to trigger the multi-farmer aggregation algorithm.
              </p>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
